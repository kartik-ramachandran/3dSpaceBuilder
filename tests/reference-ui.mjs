import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { startServer } from '../scripts/serve.mjs';
import { referenceFixtures } from './reference-fixtures.mjs';
import { PRESETS } from '../src/spec/schema.js';

const fixtures = (await referenceFixtures()).map(({ name, mediaType, buffer }) => ({ name, mimeType: mediaType, buffer }));
const server = await startServer(0);
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = []; let connected = true, requests = [], fail = false;
  page.on('pageerror', (error) => { errors.push(String(error)); console.error(error); });
  await page.route(/fonts\.(googleapis|gstatic)\.com/, (route) => route.abort());
  await page.route('https://cdn.jsdelivr.net/npm/three@0.160.0/**', (route) => route.fulfill({ path: `node_modules/three/${new URL(route.request().url()).pathname.split('/three@0.160.0/')[1]}`, contentType: 'text/javascript' }));
  await page.route('**/api/health', (route) => route.fulfill({ json: { claude: connected, references: true } }));
  await page.route('**/api/layout', async (route) => {
    requests.push(route.request().postDataJSON());
    await route.fulfill(fail ? { status: 400, json: { error: 'bad_reference', message: 'The PDF is password-protected. Upload an unlocked copy.' } } : { json: { ...PRESETS.office, name: 'Reference Studio', design: { woodColor: '#765432', upholsteryColor: '#204060' } } });
  });
  await page.goto(`http://127.0.0.1:${server.address().port}/app.html`, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.querySelector('#statusText').textContent.includes('Claude is ready'), null, { timeout: 60000 });
  await page.locator('#referenceInput').setInputFiles(fixtures);
  await page.waitForFunction(() => document.querySelector('#referenceStatus').textContent.includes('3 references ready'));
  assert.equal(await page.locator('.reference-card img').count(), 1, 'image thumbnail is visible');
  assert.equal(await page.locator('.reference-type').count(), 2, 'PDF and Word attachments are identified');
  await page.fill('#prompt', 'Use the attached brief and images. Keep the chairs blue.');
  await page.click('#buildBtn');
  await page.waitForFunction(() => document.querySelector('#spaceName').textContent === 'Reference Studio');
  assert.equal(requests[0].references.length, 3);
  assert(requests[0].prompt.includes('chairs blue'));
  assert.equal(requests[0].references[1].data, fixtures[1].buffer.toString('base64'));
  assert.equal(requests[0].references[2].data, fixtures[2].buffer.toString('base64'));
  await page.getByRole('button', { name: 'Remove chair.png', exact: true }).click();
  assert.equal(await page.locator('.reference-card').count(), 2);
  await page.fill('#prompt', ''); await page.click('#buildBtn');
  await page.waitForFunction(() => document.querySelector('#buildBtn').textContent === 'Build');
  assert.equal(requests.length, 2, 'documents can supply the entire prompt');
  assert.equal(requests[1].prompt, '');
  await page.locator('#referenceInput').setInputFiles({ name: 'unsupported.txt', mimeType: 'text/plain', buffer: Buffer.from('no') });
  await page.waitForFunction(() => document.querySelector('#referenceStatus').textContent.includes('use JPG'));
  assert.equal(await page.locator('.reference-card').count(), 2);
  fail = true; await page.click('#buildBtn');
  await page.waitForFunction(() => document.querySelector('#statusText').textContent.includes('password-protected'));
  assert.equal(await page.textContent('#spaceName'), 'Reference Studio', 'failed reference builds preserve the current scene');
  assert.equal(await page.locator('.reference-card').count(), 2, 'failed builds keep attachments for retry');
  connected = false; await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.querySelector('#statusText').textContent.includes('Offline parser'));
  await page.locator('#referenceInput').setInputFiles(fixtures[1]);
  await page.waitForFunction(() => document.querySelector('#referenceStatus').textContent.includes('1 reference ready'));
  const before = requests.length; await page.click('#buildBtn');
  await page.waitForFunction(() => document.querySelector('#statusText').textContent.includes('File-based builds need'));
  assert.equal(requests.length, before, 'offline mode does not pretend to read attachments');
  await page.setViewportSize({ width: 390, height: 844 });
  const fits = await page.locator('#dock').evaluate((el) => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; });
  assert(fits, 'attachment dock fits mobile width');
  assert.deepEqual(errors, []);
  console.log('Reference UI passed: image previews, PDF/DOCX upload, prompt + files, files-only builds, removal, errors, offline behavior, mobile width.');
} finally { await browser.close(); server.closeAllConnections(); server.close(); }
